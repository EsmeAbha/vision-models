import pexl_integration as p

HERE = Path(__file__).resolve().parent
PEXL_DOC_TYPES = HERE / 'test_files' / 'pexl' / 'doc_types.json'

ROWS = [
    {'field': 'provider_name', 'value': 'ConEd', 'verdict': 'yes', 'page': 1},
    {'field': 'total_electricity_bill', 'value': '41.32', 'verdict': 'yes', 'page': 1},
    {'field': 'billing_date', 'value': 'Sep 18, 2026', 'verdict': 'yes', 'page': 1},
    {'field': 'total_gas_bill', 'value': '', 'verdict': 'none', 'page': 1},
]


def xlsx_bytes():
    wb = Workbook(); wb.active.append(['Utility', 'Sep']); buf = io.BytesIO(); wb.save(buf)
    return buf.getvalue()


class FakePexl:
    """Answers httpx.Client.request; records every call it gets."""

    def __init__(self, post_statuses=(201,), unknown=(), timeout=False):
        self.post_statuses = list(post_statuses)
        self.unknown = list(unknown)
        self.timeout = timeout
        self.calls = []
        self.workbook = xlsx_bytes()

    def __call__(self, request):
        method, path = request.method, request.url.path
        body = json.loads(request.content) if request.content else None
        self.calls.append((method, path, body, request.headers.get('Authorization')))
        if path == '/api/v1/doc-types':
            return httpx.Response(200, json=json.loads(PEXL_DOC_TYPES.read_text()))
        if path == '/api/v1/exports':
            if self.timeout:
                raise httpx.ReadTimeout('timed out')
            status = self.post_statuses.pop(0) if len(self.post_statuses) > 1 else self.post_statuses[0]
            if status != 201:
                return httpx.Response(status, json={'detail': f'status {status}'})
            return httpx.Response(201, json={
                'id': 'e1', 'doc_type': body['doc_type'],
                'filename': 'Pexl_UtilityRecon_2026-10-13-09-30.xlsx',
                'download_path': '/api/v1/outputs/e1', 'created_at': '2026-10-13T09:30:00Z',
                'external_reference': body['external_reference'],
                'unknown_fields': self.unknown})
        if path == '/api/v1/outputs/e1':
            return httpx.Response(200, content=self.workbook)
        raise AssertionError(f'unexpected call {method} {path}')

    def posts(self):
        return [c for c in self.calls if c[1] == '/api/v1/exports']


def pexl(fake):
    """Route the Pexl client -- and only it -- to the fake. The test client is
    an httpx.Client too, so patching httpx.Client itself would catch it."""
    real = httpx.Client
    return patch.object(p.httpx, 'Client',
                        lambda **kw: real(transport=httpx.MockTransport(fake), **kw))


class ExportTests(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory(); self.addCleanup(temp.cleanup)
        self.root = Path(temp.name)
        env = patch.dict(os.environ, {'PEXL_API_URL': 'http://pexl.test', 'PEXL_API_KEY': 'k' * 40})
        env.start(); self.addCleanup(env.stop)
        nap = patch.object(p.time, 'sleep'); nap.start(); self.addCleanup(nap.stop)
        self.app = FastAPI()
        unused = lambda rid: FileResponse(__file__)
        self.store = p.mount(
            self.app, unused, unused, self.root / 'pexl',
            doc_types=lambda: [{'id': 'utility-bill', 'name': 'Utility bill',
                                'pexl': 'utility_bill', 'fields': ['total_electricity_bill']}],
            doc_type_of=lambda rid: 'utility-bill',
            run_source=lambda rid: {'filename': 'bill.pdf', 'folder_name': 'Sep', 'rows': ROWS})
        self.client = TestClient(self.app); self.addCleanup(self.client.close)

    def export(self, fake, body=None):
        with pexl(fake):
            r = self.client.post('/api/pexl/runs/run1/exports',
                                 json=body or {'doc_type': 'utility_bill', 'date_field': 'billing_date'})
            self.assertEqual(r.status_code, 202, r.text)
            for _ in range(200):
                job = self.client.get('/api/pexl/jobs/' + r.json()['id']).json()
                if job['status'] in ('completed', 'failed'):
                    return job
                time.sleep(.01)
        self.fail('export never finished')

    def test_success_posts_then_downloads(self):
        fake = FakePexl()
        job = self.export(fake)
        self.assertEqual(job['status'], 'completed', job)
        self.assertEqual(job['pexl_export_id'], 'e1')

        method, path, body, auth = fake.posts()[0]
        self.assertEqual(auth, 'Bearer ' + 'k' * 40)
        self.assertEqual(body['doc_type'], 'utility_bill')
        self.assertEqual(body['external_reference'], 'run1')
        self.assertEqual(body['options'], {'date_field': 'billing_date'})
        sent = body['files'][0]
        self.assertEqual((sent['filename'], sent['folder_name']), ('bill.pdf', 'Sep'))
        by_field = {r['field']: r for r in sent['rows']}
        self.assertEqual(by_field['billing_date']['value'], '09/18/2026', 'date not sent as MM/DD/YYYY')
        self.assertIsNone(by_field['total_gas_bill']['value'], 'a missing value must be null')
        self.assertEqual(by_field['total_electricity_bill']['page'], 1)
        self.assertEqual(set(by_field['provider_name']), {'page', 'field', 'value', 'confidence'})

        # The download is the bytes Pexl returned, under Pexl's file name.
        out = job['outputs'][0]
        self.assertEqual(out['filename'], 'Pexl_UtilityRecon_2026-10-13-09-30.xlsx')
        got = self.client.get(out['download'])
        self.assertEqual(got.content, fake.workbook)
        self.assertIn('Pexl_UtilityRecon', got.headers['content-disposition'])
        # And it is kept against the run.
        self.assertEqual([j['id'] for j in self.client.get('/api/pexl/runs/run1/jobs').json()], [job['id']])

    def test_date_option_only_for_utility_bills(self):
        fake = FakePexl()
        self.export(fake, {'doc_type': 'bank_statement', 'date_field': 'billing_date'})
        self.assertNotIn('options', fake.posts()[0][2])

    def test_unknown_fields_are_warned_with_the_run(self):
        with self.assertLogs('pexl', level='WARNING') as logs:
            job = self.export(FakePexl(unknown=['meter_number']))
        self.assertEqual(job['status'], 'completed')
        self.assertEqual(job['unknown_fields'], ['meter_number'])
        self.assertTrue(any('run1' in line and 'meter_number' in line for line in logs.output), logs.output)

    def test_422_fails_without_retrying(self):
        fake = FakePexl(post_statuses=(422,))
        job = self.export(fake)
        self.assertEqual(job['status'], 'failed')
        self.assertIn('status 422', job['error'], 'Pexl\'s detail should reach the user')
        self.assertEqual(len(fake.posts()), 1)

    def test_401_fails_without_retrying(self):
        fake = FakePexl(post_statuses=(401,))
        job = self.export(fake)
        self.assertEqual(job['status'], 'failed')
        self.assertIn('key is invalid', job['error'])
        self.assertEqual(len(fake.posts()), 1)

    def test_503_retries_with_backoff(self):
        fake = FakePexl(post_statuses=(503, 503, 201))
        job = self.export(fake)
        self.assertEqual(job['status'], 'completed', job)
        self.assertEqual(len(fake.posts()), 3)

    def test_503_gives_up_after_three_tries(self):
        fake = FakePexl(post_statuses=(503,))
        job = self.export(fake)
        self.assertEqual(job['status'], 'failed')
        self.assertEqual(len(fake.posts()), 3)

    def test_500_retries_once(self):
        fake = FakePexl(post_statuses=(500,))
        job = self.export(fake)
        self.assertEqual(job['status'], 'failed')
        self.assertEqual(len(fake.posts()), 2)

    def test_a_timed_out_post_is_never_resent(self):
        fake = FakePexl(timeout=True)
        job = self.export(fake)
        self.assertEqual(job['status'], 'failed')
        self.assertIn('do not automatically resubmit', job['error'])
        self.assertEqual(len(fake.posts()), 1)

    def test_timeout_is_long_enough_for_pexl(self):
        self.assertGreaterEqual(p.TIMEOUT, 150)

    def test_refused_before_anything_is_sent(self):
        fake = FakePexl()
        with pexl(fake):
            self.assertEqual(self.client.post('/api/pexl/runs/run1/exports', json={}).status_code, 422)
            with patch.dict(os.environ, {'PEXL_API_KEY': ''}):
                self.assertEqual(self.client.post('/api/pexl/runs/run1/exports',
                                                  json={'doc_type': 'utility_bill'}).status_code, 503)
            self.assertEqual(fake.posts(), [])

    def test_setup_offers_pexl_types_and_picks_the_runs(self):
        with pexl(FakePexl()):
            setup = self.client.get('/api/pexl/runs/run1/setup').json()
        self.assertEqual(setup['pexl_type'], 'utility_bill')
        self.assertEqual([t['value'] for t in setup['pexl_types']],
                         ['utility_bill', 'bank_statement', 'appraisal', 'lease_contract', 'tax', 'others'])

    def test_url_defaults_to_the_deployed_pexl(self):
        with patch.dict(os.environ, {'PEXL_API_URL': ''}):
            self.assertEqual(p.Client().url, 'https://pexlbackend.bulkscraper.cloud')


def twelve_bills():
    """One PDF, twelve monthly electric bills: what the field search returns
    for it -- the amount found only as 'total amount due', with text after."""
    rows, pages = [], []
    for month in range(1, 13):
        rows += [
            {'field': 'billing_date', 'value': f'2026-{month:02d}-05', 'verdict': 'yes', 'page': month},
            {'field': 'total_electricity_bill', 'value': '', 'verdict': 'none', 'page': month},
            {'field': 'total_utilities', 'value': f'${100 + month}.28 DUE BY {month:02d}/26/2026',
             'verdict': 'yes', 'page': month},
        ]
        pages.append(f'<!-- ===== page {month} ===== -->\nACCOUNT EL-1\nUsage 640 kWh\n'
                     f'TOTAL AMOUNT DUE: ${100 + month}.28')
    rows.insert(0, {'field': 'account_number', 'value': 'EL-1', 'verdict': 'yes', 'page': 1})
    rows.insert(0, {'field': 'property_name', 'value': '482 Maple Avenue', 'verdict': 'yes', 'page': 1})
    return rows, '\n'.join(pages)


class UtilityBillTests(unittest.TestCase):
    """Pexl fills its utility sheet only from total_<utility>_bill amounts
    with a date on the same page. A bill prints 'total amount due', so the
    first live export came back with headers and nothing else."""

    def setUp(self):
        temp = tempfile.TemporaryDirectory(); self.addCleanup(temp.cleanup)
        env = patch.dict(os.environ, {'PEXL_API_URL': 'http://pexl.test', 'PEXL_API_KEY': 'k' * 40})
        env.start(); self.addCleanup(env.stop)
        nap = patch.object(p.time, 'sleep'); nap.start(); self.addCleanup(nap.stop)
        self.source = {'filename': 'electric_bills_12_months.pdf', 'folder_name': '', 'rows': [], 'text': ''}
        self.app = FastAPI()
        unused = lambda rid: FileResponse(__file__)
        p.mount(self.app, unused, unused, Path(temp.name) / 'pexl', run_source=lambda rid: self.source)
        self.client = TestClient(self.app); self.addCleanup(self.client.close)

    def send(self, fake):
        with pexl(fake):
            r = self.client.post('/api/pexl/runs/run1/exports', json={'doc_type': 'utility_bill'})
            if r.status_code != 202:
                return r, None
            for _ in range(200):
                job = self.client.get('/api/pexl/jobs/' + r.json()['id']).json()
                if job['status'] in ('completed', 'failed'):
                    return r, job
                time.sleep(.01)
        self.fail('export never finished')

    def test_twelve_monthly_bills_go_as_pages_1_to_12(self):
        self.source['rows'], self.source['text'] = twelve_bills()
        fake = FakePexl()
        _, job = self.send(fake)
        self.assertEqual(job['status'], 'completed', job)
        sent = fake.posts()[0][2]['files'][0]['rows']
        for month in range(1, 13):
            on_page = {r['field']: r['value'] for r in sent if r['page'] == month and r['value']}
            with self.subTest(page=month):
                self.assertEqual(on_page.get('total_electricity_bill'), f'{100 + month}.28')
                self.assertRegex(on_page.get('billing_date', ''), r'^\d{2}/\d{2}/\d{4}$')
                self.assertEqual(on_page['billing_date'], f'{month:02d}/05/2026')
        # The request is kept, so an empty sheet can be traced to what was sent.
        self.assertEqual(job['request']['files'][0]['rows'], sent)
        self.assertEqual(len(job['notes']), 12)

    def test_tax_inside_the_total_is_not_added_twice(self):
        rows = p.export_rows([{'field': 'total_utilities', 'value': '$102.28 DUE BY 09/26/2026', 'verdict': 'yes', 'page': 1},
                              {'field': 'taxes', 'value': '5.71', 'verdict': 'yes', 'page': 1},
                              {'field': 'billing_date', 'value': '09/05/2026', 'verdict': 'yes', 'page': 1}])
        out, notes, usable = p.prepare_utility_rows(rows, 'Usage 675 kWh. State Sales Tax 5.71. Total 102.28')
        got = {r['field']: r['value'] for r in out}
        self.assertEqual(got['total_electricity_bill'], '102.28')
        self.assertIsNone(got['taxes'], 'the tax inside the total would be added to it again')
        self.assertIn('already in it', notes[0])
        self.assertEqual(usable, 1)

    def test_no_amounts_means_nothing_is_sent(self):
        self.source['rows'] = [{'field': 'billing_date', 'value': '09/05/2026', 'verdict': 'yes', 'page': 1},
                               {'field': 'account_number', 'value': 'EL-1', 'verdict': 'yes', 'page': 1}]
        fake = FakePexl()
        r, _ = self.send(fake)
        self.assertEqual(r.status_code, 422)
        self.assertIn('No utility amounts found for this document', r.json()['detail'])
        self.assertEqual(fake.posts(), [])

    def test_amounts_start_with_the_number(self):
        for raw, want in [('$102.28 DUE BY 09/26/2026', '102.28'), ('USD 55.10', '55.10'),
                          ('Amount: 41.32', '41.32'), ('$1,204.10', '1204.10'),
                          ('(12.00)', '-12.00'), ('-$ 5.00', '-5.00'), ('n/a', None)]:
            self.assertEqual(p.clean_amount(raw), want, raw)

    def test_a_combined_bill_is_not_split_by_guessing(self):
        rows = p.export_rows([{'field': 'total_utilities', 'value': '$90.00', 'verdict': 'yes', 'page': 1},
                              {'field': 'date', 'value': '09/05/2026', 'verdict': 'yes', 'page': 1}])
        out, notes, usable = p.prepare_utility_rows(rows, 'Water 4,000 gallons. Electric 300 kWh.')
        self.assertFalse(any(r['field'] == 'total_electricity_bill' for r in out))
        self.assertEqual(usable, 0)
        self.assertIn('not split', notes[0])

    def test_water_and_sewer_together_is_its_own_field(self):
        rows = p.export_rows([{'field': 'total_utilities', 'value': '$64.10', 'verdict': 'yes', 'page': 1},
                              {'field': 'date', 'value': '09/05/2026', 'verdict': 'yes', 'page': 1}])
        out, _, usable = p.prepare_utility_rows(rows, 'Water usage 3,000 gallons; sewer service charge')
        self.assertEqual({r['field']: r['value'] for r in out}.get('total_water_sewer_bill'), '64.10')
        self.assertEqual(usable, 1)


class FieldMappingTests(unittest.TestCase):
    """Every FinAi field for a type must be a field of the Pexl type it maps to,
    or its value only lands on Pexl's Plain Data sheet."""

    def test_finai_fields_exist_in_pexl(self):
        import vision_server
        pexl = {t['value']: {f['value'] for f in t['fields']}
                for t in json.loads(PEXL_DOC_TYPES.read_text())}
        for d in vision_server.api_doc_types():
            target = d['pexl'] or 'others'
            with self.subTest(finai=d['id'], pexl=target):
                self.assertIn(target, pexl, f'Pexl has no document type {target}')
                if pexl[target]:  # 'others' takes any field name
                    missing = [f for f in d['fields'] if f not in pexl[target]]
                    self.assertEqual(missing, [], f'not in Pexl {target}')

    def test_dates_become_mm_dd_yyyy(self):
        for raw in ('09/18/2026', '9/18/26', '2026-09-18', 'Sep 18, 2026', 'September 18 2026', '18 Sep 2026'):
            self.assertEqual(p.us_date(raw), '09/18/2026', raw)
        self.assertEqual(p.us_date('due on receipt'), 'due on receipt')


@unittest.skipUnless(os.environ.get('PEXL_API_KEY'), 'set PEXL_API_KEY to run against live Pexl')
class LiveTests(unittest.TestCase):
    def test_small_utility_bill_round_trip(self):
        api = p.Client()
        types = api.request('GET', '/api/v1/doc-types').json()
        self.assertIn('utility_bill', [t['value'] for t in types])
        result = api.request('POST', '/api/v1/exports', json={
            'doc_type': 'utility_bill', 'external_reference': 'finai-live-test',
            'options': {'date_field': 'auto'},
            'files': [{'filename': 'live-test.pdf', 'folder_name': '',
                       'rows': p.export_rows(ROWS)}]}).json()
        self.assertEqual(result['unknown_fields'], [])
        content = api.request('GET', result['download_path']).content
        wb = load_workbook(io.BytesIO(content))
        self.assertTrue(wb.sheetnames)
        wb.close()


