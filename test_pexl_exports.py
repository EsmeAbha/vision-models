"""Pexl export by document type: FinAi sends values plus a type, Pexl builds
its standard workbook, FinAi downloads it. No template, no column mapping.

Pexl is mocked at the HTTP layer, so the retry rules are exercised for real.
test_files/pexl/doc_types.json is Pexl's own /api/v1/doc-types output,
generated by its export runtime (dist-server/export-workbook.mjs doc-types).

The live test runs only when PEXL_API_KEY is set.
"""
